function a = sensitivity_arithmetic(T)
% DOCUMENTED Table7 arithmetic only, not a regenerated sensitivity experiment.
F=T.F; S=T.Stability; g=T.Field;
assert(all(diff(F)>0),'targets:order','F must increase');
a=struct('definition','DeltaY/DeltaF; no original regression fitting', ...
 'stabilityEndpoint',(S(end)-S(1))/(F(end)-F(1)), ...
 'fieldEndpoint',(g(end)-g(1))/(F(end)-F(1)), ...
 'stabilityAdjacent',diff(S)./diff(F),'fieldAdjacent',diff(g)./diff(F), ...
 'printedStabilityCoefficient',.00866,'printedFieldCoefficient',-.05872);
a.stabilityDifference=a.stabilityEndpoint-a.printedStabilityCoefficient;
a.fieldDifference=a.fieldEndpoint-a.printedFieldCoefficient;
end
